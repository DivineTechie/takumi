import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync, execSync } from 'node:child_process';
import { compile } from 'json-schema-to-typescript';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

const schemaDir = path.join(rootDir, 'shared', 'schema');
const tsDir = path.join(schemaDir, 'ts');
const pyDir = path.join(schemaDir, 'py');

const schemas = [
  'captures',
  'skills',
  'forge_jobs',
  'forge_job_events',
  'review_requests',
  'sessions',
  'session_events',
  'products',
  'units',
  'inspections',
  'machines',
  'machine_events',
  'soak_runs',
];

// Ensure target directories exist
fs.mkdirSync(tsDir, { recursive: true });
fs.mkdirSync(pyDir, { recursive: true });

// Locate datamodel-codegen in .venv
function findDatamodelCodegen() {
  const isWin = process.platform === 'win32';
  const binName = isWin ? 'datamodel-codegen.exe' : 'datamodel-codegen';
  const venvBinDir = isWin ? path.join(rootDir, '.venv', 'Scripts') : path.join(rootDir, '.venv', 'bin');
  const exePath = path.join(venvBinDir, binName);

  if (!fs.existsSync(exePath)) {
    console.error('\n[ERROR] datamodel-codegen was not found in .venv!');
    console.error('Please set up the virtual environment and install dev dependencies:');
    console.error('  python -m venv .venv');
    if (isWin) {
      console.error('  .\\.venv\\Scripts\\python -m pip install -r requirements-dev.txt');
    } else {
      console.error('  ./.venv/bin/pip install -r requirements-dev.txt');
    }
    console.error('');
    process.exit(1);
  }
  return exePath;
}

const datamodelCodegenPath = findDatamodelCodegen();

async function generate() {
  console.log('Generating TypeScript types and Pydantic v2 models from schemas...');

  for (const name of schemas) {
    const jsonPath = path.join(schemaDir, `${name}.json`);
    const tsPath = path.join(tsDir, `${name}.ts`);
    const pyPath = path.join(pyDir, `${name}.py`);

    console.log(`Processing ${name}.json...`);

    // 1. Generate TypeScript
    const rawSchema = JSON.parse(fs.readFileSync(jsonPath, 'utf-8'));
    const tsCode = await compile(rawSchema, rawSchema.title || name, {
      bannerComment: '/* eslint-disable */\n/**\n * Auto-generated by json-schema-to-typescript\n * Do not modify directly.\n */\n',
      additionalProperties: false,
    });
    fs.writeFileSync(tsPath, tsCode, 'utf-8');

    // 2. Generate Pydantic v2
    execFileSync(
      datamodelCodegenPath,
      [
        '--input',
        jsonPath,
        '--output',
        pyPath,
        '--input-file-type',
        'jsonschema',
        '--output-model-type',
        'pydantic_v2.BaseModel',
        '--formatters',
        'builtin',
        '--disable-timestamp',
      ],
      { stdio: 'inherit' }
    );
  }

  // Create TypeScript index re-exports
  const tsIndexContent = `/* eslint-disable */
/**
 * Auto-generated schema type re-exports.
 */
${schemas.map((name) => `export * from './${name}.js';`).join('\n')}
`;
  fs.writeFileSync(path.join(tsDir, 'index.ts'), tsIndexContent, 'utf-8');

  // Create Python __init__.py re-exports
  const pyInitLines = [
    '# Auto-generated schema models re-export',
    'from __future__ import annotations',
    '',
  ];
  for (const name of schemas) {
    pyInitLines.push(`from shared.schema.py import ${name}`);
  }
  fs.writeFileSync(path.join(pyDir, '__init__.py'), pyInitLines.join('\n') + '\n', 'utf-8');

  // Verify TypeScript typecheck on generated re-exports
  console.log('Typechecking generated TypeScript types...');
  execSync(`npx --no-install tsc --noEmit -p "${path.join(schemaDir, 'tsconfig.json')}"`, {
    stdio: 'inherit',
    cwd: rootDir,
  });

  console.log('Schema generation & TypeScript typecheck complete!');
}

generate().catch((err) => {
  console.error('Schema generation failed:', err);
  process.exit(1);
});
